export function getDefaultTheme(): FestivalTheme {
  return festivalThemes.find(t => t.slug === 'default')!;
}

export function getScheduledTheme(): FestivalTheme | null {
  const today = new Date();
  const currentMonth = today.getMonth() + 1;
  const currentDay = today.getDate();

  const scheduledThemes = festivalThemes
    .filter(t => t.schedule && t.status === 'scheduled')
    .filter(t => {
      if (!t.schedule?.startDate || !t.schedule?.endDate) return false;
      
      const startDate = new Date(t.schedule.startDate);
      const endDate = new Date(t.schedule.endDate);
      
      // For recurring yearly themes, check month/day only
      if (t.schedule.recurringYearly) {
        const startMonth = startDate.getMonth() + 1;
        const startDay = startDate.getDate();
        const endMonth = endDate.getMonth() + 1;
        const endDay = endDate.getDate();
        
        // Handle year boundary (e.g., Dec 30 - Jan 3)
        if (startMonth > endMonth || (startMonth === endMonth && startDay > endDay)) {
          return (currentMonth > startMonth || (currentMonth === startMonth && currentDay >= startDay)) ||
                 (currentMonth < endMonth || (currentMonth === endMonth && currentDay <= endDay));
        }
        
        return (currentMonth > startMonth || (currentMonth === startMonth && currentDay >= startDay)) &&
               (currentMonth < endMonth || (currentMonth === endMonth && currentDay <= endDay));
      }
      
      // For non-recurring, check full date
      return today >= startDate && today <= endDate;
    })
    .sort((a, b) => (b.schedule?.priority || 0) - (a.schedule?.priority || 0));

  return scheduledThemes[0] || null;
}

export function getThemeById(id: string): FestivalTheme | undefined {
  return festivalThemes.find(t => t.id === id);
}
